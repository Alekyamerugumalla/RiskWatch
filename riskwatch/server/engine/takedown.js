// Generates a ready-to-review takedown / abuse report for a flagged entity or a whole campaign.
// Output is a DRAFT: a human analyst reviews and submits it through the platform's own report channel.

const PLATFORMS = {
  instagram: { name: 'Instagram (Meta)', kind: 'account', ask: 'impersonation / fake business account' },
  facebook: { name: 'Facebook (Meta)', kind: 'account', ask: 'impersonation / fake business account' },
  x: { name: 'X', kind: 'account', ask: 'impersonation and deceptive-identity violation' },
  telegram: { name: 'Telegram', kind: 'account', ask: 'scam / impersonation channel' },
  android: { name: 'Google Play / hosting provider', kind: 'app', ask: 'malware and brand-impersonation app' },
};

const fmtSignals = (a) =>
  a.signals.filter((s) => s.points >= 3).sort((x, y) => y.points - x.points).map((s) => `  - ${s.label}: ${s.evidence}`).join('\n');

const fmtIndicators = (ind) =>
  [
    ...ind.links.map((l) => `  - Link: ${l}`),
    ...ind.upi.map((u) => `  - UPI ID: ${u}`),
    ...ind.phones.map((p) => `  - Phone/WhatsApp: ${p}`),
    ...(ind.hashes || []).map((h) => `  - File hash: ${h}`),
  ].join('\n');

export function takedownForEntity(a, brand, campaign) {
  const p = PLATFORMS[a.platform] || (a.type === 'app' ? PLATFORMS.android : { name: a.platform, kind: 'account', ask: 'impersonation / fake account' });
  const subject = a.type === 'app'
    ? `Report: malicious app impersonating ${brand.name} (${a.raw.packageName})`
    : `Report: ${p.ask} impersonating ${brand.name} (@${a.raw.handle})`;
  const body = `To: ${p.name} Trust & Safety / Brand Rights team

We are the authorised brand-protection team for ${brand.name} ${brand.officialDomains?.[0] ? `(official site: https://${brand.officialDomains[0]})` : ''}.
We are reporting the following ${a.type} for ${p.ask}.

REPORTED ${a.type.toUpperCase()}
  - ${a.type === 'app' ? `${a.title} (${a.raw.packageName}), distributed via ${a.raw.store}` : `${a.title} (display name "${a.raw.displayName}") on ${p.name}`}
  - Risk assessment: ${a.score}/100 (${a.level})

OFFICIAL ASSETS FOR COMPARISON
${brand.officialHandles?.length ? `  - Official handles: ${brand.officialHandles.map((h) => '@' + h).join(', ')}\n` : ''}${brand.officialApp?.package ? `  - Official app: ${brand.officialApp.package}${brand.officialApp.developer ? ` (developer: ${brand.officialApp.developer})` : ''}\n` : ''}  - Brand name: ${brand.name}

EVIDENCE
${fmtSignals(a)}
${fmtIndicators(a.indicators) ? `\nINDICATORS\n${fmtIndicators(a.indicators)}\n` : ''}${campaign ? `\nThis ${a.type} is part of a coordinated operation ("${campaign.name}") involving ${campaign.members.length} linked assets across ${campaign.platforms.join(', ')}. Linked assets are listed in the attached campaign report.\n` : ''}
REQUESTED ACTION
  Please review and remove or suspend this ${a.type} for violating your impersonation, fraud and deceptive-behaviour policies, and preserve related data for potential law-enforcement requests.

Authorisation: [attach letter of authority / trademark registration number]
Contact: [brand-protection analyst name, email]
Generated by RiskWatch on ${new Date().toISOString().slice(0, 10)}. DRAFT: requires analyst review before submission.`;
  return { subject, platform: p.name, body };
}

export function takedownForCampaign(c, analysesById, brand) {
  const members = c.members.map((id) => analysesById.get(id));
  const lines = members.map((m) => `  - [${m.level} ${m.score}] ${m.title} (${m.type === 'app' ? 'android app' : m.platform})`).join('\n');
  const shared = c.sharedIndicators.map((s) => `  - ${s.type}: ${s.value} (seen on ${s.entityIds.length} assets)`).join('\n');
  const body = `CAMPAIGN REPORT: ${c.name}
Brand: ${brand.name}   |   Peak risk: ${c.riskScore}/100   |   Assets: ${c.members.length} (${c.accounts} account${c.accounts === 1 ? '' : 's'}, ${c.apps} app${c.apps === 1 ? '' : 's'})
Platforms: ${c.platforms.join(', ')}

WHY THESE ARE ONE OPERATION
Shared indicators connect every asset below to the same operator:
${shared}

ASSETS TO ACTION
${lines}

RECOMMENDED RESPONSE
  1. Submit the per-asset takedown drafts to each platform (one per asset below).
  2. Report the shared domain / UPI ID / phone number to the hosting provider, bank/UPI provider and telecom operator.
  3. Warn customers via the brand's official channels; never ask for OTP/PIN in the warning.
  4. File a cybercrime complaint with the combined evidence.

Generated by RiskWatch on ${new Date().toISOString().slice(0, 10)}. DRAFT: requires analyst review.`;
  return { subject: `Campaign report: ${c.name}`, platform: 'Internal / law enforcement', body };
}
